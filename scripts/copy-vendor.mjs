// ينسخ المكتبات والخطوط من node_modules إلى www عشان التطبيق يشتغل بدون إنترنت
import { copyFileSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const nm = 'node_modules';
const out = 'www';
mkdirSync(join(out, 'vendor'), { recursive: true });
mkdirSync(join(out, 'fonts'), { recursive: true });

function cp(from, to) {
  if (!existsSync(from)) { console.error('✗ مفقود: ' + from + '  (شغّل npm install)'); process.exit(1); }
  copyFileSync(from, to);
  console.log('✓ ' + to);
}

cp(join(nm, 'jszip/dist/jszip.min.js'), join(out, 'vendor/jszip.min.js'));
cp(join(nm, 'lucide/dist/umd/lucide.min.js'), join(out, 'vendor/lucide.min.js'));

const fonts = [
  { pkg: '@fontsource/inter', id: 'inter', family: 'Inter', weights: [300, 400, 500, 600, 700, 800] },
  { pkg: '@fontsource/jetbrains-mono', id: 'jetbrains-mono', family: 'JetBrains Mono', weights: [400, 500, 600] },
  { pkg: '@fontsource/ibm-plex-sans-arabic', id: 'ibm-plex-sans-arabic', family: 'IBM Plex Sans Arabic', weights: [300, 400, 500, 600, 700], subset: 'arabic', range: 'U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0897-08E1,U+08E3-08FF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,U+FE70-FE74,U+FE76-FEFC' }
];
let css = '/* generated by scripts/copy-vendor.mjs */\n';
for (const f of fonts) {
  for (const w of f.weights) {
    const file = `${f.id}-${f.subset || 'latin'}-${w}-normal.woff2`;
    cp(join(nm, f.pkg, 'files', file), join(out, 'fonts', file));
    css += `@font-face{font-family:'${f.family}';font-style:normal;font-weight:${w};font-display:swap;src:url('./${file}') format('woff2');${f.range ? `unicode-range:${f.range};` : ''}}\n`;
  }
}
writeFileSync(join(out, 'fonts/fonts.css'), css);
console.log('✓ www/fonts/fonts.css');
